def write_multiqc(result: ScanResult, output_dir: Path) -> Path:
    """Write a MultiQC custom-content directory and return its path."""

    if output_dir.suffix.lower() in {".yaml", ".yml"}:
        raise ValueError(f"dicomqc writes MultiQC custom content as a directory, not a YAML file: {output_dir}")
    output_dir.mkdir(parents=True, exist_ok=True)
    _clear_existing_bundle(output_dir)
    _write_text(output_dir, "dicomqc_00_overview_mqc.html", build_overview_html(result))
    _write_yaml(output_dir, "dicomqc_summary_mqc.yaml", build_summary_payload(result))
    _write_yaml(output_dir, "dicomqc_01_release_status_mqc.yaml", build_release_status_payload(result))
    _write_yaml(output_dir, "dicomqc_02_findings_mqc.yaml", build_findings_payload(result))
    return output_dir


def build_overview_html(result: ScanResult) -> str:
    status_label, status = audit_status(result)
    status_note = audit_guidance(result)
    policy_meta = ""
    if result.policy is not None:
        policy_meta = (
            f'<p>Project policy: <code>{escape(result.policy["id"])}</code> · Additive checks</p>'
            f'<p>Policy SHA-256: <code style="overflow-wrap:anywhere">{escape(result.policy["sha256"])}</code></p>'
        )
    vendor_panel = (
        '<details class="vendor-panel"><summary>Scanner and private-tag inventory</summary>'
        + render_vendor_inventory(result.vendor_summary) + '</details>'
    ) if result.vendor_summary is not None else ""
    privacy_note = (
        "Vendor inventory includes observed metadata labels. Findings omit raw tag values."
        if vendor_panel else "Raw tag values are omitted."
    )

    return f"""<!--
id: dicomqc_00_overview
parent_id: dicomqc
parent_name: dicomqc
parent_description: DICOM metadata quality-control summaries generated by dicomqc.
section_name: dicomqc audit overview
description: At-a-glance metadata audit summary for the scanned DICOM dataset.
plot_type: html
-->
<style>{OVERVIEW_STYLE}{VENDOR_STYLE if vendor_panel else ""}</style>
<div class="dicomqc-dashboard dicomqc-status-{status}">
  <div class="dicomqc-status-card">
    <span class="dicomqc-label">Audit status</span>
    <strong>{status_label}</strong>
    <p>{status_note}</p>
  </div>
  <div class="dicomqc-metrics">
    <div><span>{result.files_scanned}</span><small>Files read</small></div>
    <div><span>{result.error_count}</span><small>Errors</small></div>
    <div><span>{result.warning_count}</span><small>Warnings</small></div>
    <div><span>{len(result.skipped_files)}</span><small>Unreadable files</small></div>
  </div>
  <details><summary>Audit scope and report notes</summary>
    <p>Metadata audit only. Pixels and facial features are not inspected. A passing result is not approval to share data.</p>
    <p>{privacy_note} File paths may still identify people; review reports before sharing.</p>
    {policy_meta}
    {render_uid_coverage(result.uid_checks)}
  </details>
  {vendor_panel}
</div>
"""


def build_summary_payload(result: ScanResult) -> dict[str, Any]:
    data = {
        "dicomqc": {
            "files_scanned": result.files_scanned,
            "errors": result.error_count,
            "warnings": result.warning_count,
            "skipped_files": len(result.skipped_files),
            "private_tag_findings": sum(1 for finding in result.findings if finding.keyword == "PrivateTags"),
        }
    }
    headers = {
        "files_scanned": {
            "title": "Files read",
            "description": "DICOM files successfully scanned",
            "scale": "Blues",
        },
        "errors": {
            "title": "dicomqc errors",
            "description": "Validation errors reported by dicomqc",
            "scale": "Reds",
        },
        "warnings": {
            "title": "dicomqc warnings",
            "description": "Warnings reported by dicomqc",
            "scale": "YlOrBr",
        },
        "skipped_files": {
            "title": "Unreadable files",
            "description": "Files that could not be read as DICOM",
            "scale": "Purples",
        },
        "private_tag_findings": {
            "title": "Private tag files",
            "description": "Files with private-tag findings",
            "scale": "Oranges",
        },
    }
    return _section_payload(
        "dicomqc_summary",
        "dicomqc summary",
        "dicomqc metadata validation summary for MultiQC general statistics.",
        "generalstats",
        data,
        headers=headers,
    )


def build_findings_payload(result: ScanResult) -> dict[str, Any]:
    severity_order = {"error": 0, "warning": 1, "info": 2}
    rows = {
        f"finding_{index:03d}": {
            "file": finding.path,
            "severity": finding.severity.value,
            "rule_id": finding.rule_id,
            "tag": finding.tag or "",
            "keyword": finding.keyword or "",
            "value_state": finding.value_state.value,
            "message": finding.message,
            "recommendation": finding.recommendation,
        }
        for index, finding in enumerate(sorted(result.findings, key=lambda item: severity_order[item.severity.value]), start=1)
    }
    return _section_payload(
        "dicomqc_02_findings",
        "dicomqc findings and recommended actions",
        "Metadata findings and next steps. Raw tag values are omitted. dicomqc never modifies files.",
        "table",
        rows,
        pconfig={"id": "dicomqc_findings_table", "title": "dicomqc findings and recommended actions", "col1_header": "Finding ID"},
        headers={
            "severity": {
                "title": "Severity",
                "description": "dicomqc finding severity",
                "bgcols": {"error": "#fce8e4", "warning": "#fff2cf", "info": "#dff1f2"},
            },
            "file": {"title": "File", "description": "Relative DICOM file path", "scale": False},
            "keyword": {"title": "Keyword", "description": "DICOM keyword or finding group", "hidden": True, "scale": False},
            "tag": {"title": "Tag", "description": "DICOM tag when applicable", "hidden": True, "scale": False},
            "value_state": {
                "title": "Value state",
                "hidden": True,
                "description": "Redaction-safe value state",
                "bgcols": {"present": "#f97316", "empty": "#94a3b8", "absent": "#22c55e"},
            },
            "rule_id": {"title": "Rule", "description": "Stable dicomqc rule identifier", "scale": False, "hidden": True},
            "message": {"title": "Finding", "description": "Finding summary", "scale": False},
            "recommendation": {"title": "Next step", "description": "Recommended action using external tools", "scale": False},
        },
    )


